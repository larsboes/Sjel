/** Generate discovery and TypeScript from Rust's object declaration. */
import { writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '../..');
const result = Bun.spawnSync(['sjel', 'cargo', 'run', '--locked', '--quiet', '-p', 'projects-api', '--example', 'catalog'], { cwd: root, stderr: 'inherit' });
if (result.exitCode !== 0) throw new Error('Rust catalog export failed');
const registry = JSON.parse(result.stdout.toString());
type Schema = { $ref?: string; $defs?: Record<string, Schema>; type?: string | string[]; enum?: unknown[]; properties?: Record<string, Schema>; required?: string[]; items?: Schema };

// This lowering accepts only the wire shapes used by registered projections.
function typeOf(schema: Schema, definitions: Record<string, Schema>): string {
  if (schema.$ref) {
    const target = definitions[schema.$ref.replace('#/$defs/', '')];
    if (!target) throw new Error(`Unresolved schema reference ${schema.$ref}`);
    return typeOf(target, definitions);
  }
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(type => typeOf({ ...schema, type }, definitions)).join(' | ');
  switch (schema.type) {
    case 'object': return `{\n${Object.entries(schema.properties ?? {}).map(([key, value]) => `  ${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${typeOf(value, definitions)};`).join('\n')}\n}`;
    case 'array': if (!schema.items) throw new Error('Missing array items'); return `Array<${typeOf(schema.items, definitions)}>`;
    case 'integer': case 'number': return 'number';
    case 'string': case 'boolean': case 'null': return schema.type;
    default: throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`);
  }
}
const types = registry.objects.map((object: { id: string; schema: Schema }) => `  ${JSON.stringify(object.id)}: ${typeOf(object.schema, object.schema.$defs ?? {})};`).join('\n');
const files = {
  'src/registry.json': JSON.stringify(registry, null, 2) + '\n',
  'src/objects.ts': `// Generated by bun run generate; edit the Rust declaration.\nexport type Objects = {\n${types}\n};\n`,
};
for (const [file, content] of Object.entries(files)) {
  const path = resolve(import.meta.dir, file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`Stale generated artifact: ${file}`);
  } else writeFileSync(path, content);
}
